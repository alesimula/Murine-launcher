package com.android.internal.org.bouncycastle.crypto.util;

public abstract class Pack {
    public Pack() {}
    public static int bigEndianToInt(byte[] p0, int p1) { return 0; }
    public static void bigEndianToInt(byte[] p0, int p1, int[] p2) {}
    public static byte[] intToBigEndian(int p0) { return null; }
    public static void intToBigEndian(int p0, byte[] p1, int p2) {}
    public static byte[] intToBigEndian(int[] p0) { return null; }
    public static void intToBigEndian(int[] p0, byte[] p1, int p2) {}
    public static long bigEndianToLong(byte[] p0, int p1) { return 0L; }
    public static void bigEndianToLong(byte[] p0, int p1, long[] p2) {}
    public static byte[] longToBigEndian(long p0) { return null; }
    public static void longToBigEndian(long p0, byte[] p1, int p2) {}
    public static byte[] longToBigEndian(long[] p0) { return null; }
    public static void longToBigEndian(long[] p0, byte[] p1, int p2) {}
    public static int littleEndianToInt(byte[] p0, int p1) { return 0; }
    public static void littleEndianToInt(byte[] p0, int p1, int[] p2) {}
    public static void littleEndianToInt(byte[] p0, int p1, int[] p2, int p3, int p4) {}
    public static byte[] intToLittleEndian(int p0) { return null; }
    public static void intToLittleEndian(int p0, byte[] p1, int p2) {}
    public static byte[] intToLittleEndian(int[] p0) { return null; }
    public static void intToLittleEndian(int[] p0, byte[] p1, int p2) {}
    public static long littleEndianToLong(byte[] p0, int p1) { return 0L; }
    public static void littleEndianToLong(byte[] p0, int p1, long[] p2) {}
    public static byte[] longToLittleEndian(long p0) { return null; }
    public static void longToLittleEndian(long p0, byte[] p1, int p2) {}
    public static byte[] longToLittleEndian(long[] p0) { return null; }
    public static void longToLittleEndian(long[] p0, byte[] p1, int p2) {}
}
